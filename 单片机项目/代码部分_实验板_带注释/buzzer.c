// 无源蜂鸣器
/*
单片机驱动无源蜂鸣器演奏音乐，核心原理是**输出特定频率的方波信号**，
而非改变电压的高低数值。无源蜂鸣器内部无振荡源，必须依赖外部脉冲来驱动：
当单片机I/O口以固定频率快速切换高低电平（即输出方波）时，
蜂鸣器内的压电片或电磁线圈会随电平跳变而机械振动，从而发出声音。
方波的频率决定了振动的快慢，也就决定了音调的高低——频率越高，
声音越尖锐；频率越低，声音越低沉。音乐中的每个音符（Do、Re、Mi等）都对应一个标准频率，
因此只需查表得到音符的频率值，再用单片机的定时器产生该频率的方波，即可发出对应的音调。
同时，通过控制每个方波持续输出的时间（即延时或定时器计时），就能决定音符的节拍长短。
将乐谱中的音符和节拍逐一转换为频率与时长序列，由单片机依次输出对应的方波，
蜂鸣器便会连续奏出旋律。为获得足够驱动电流，通常还需用三极管搭建开关电路放大信号。
简而言之：频率定音调，时长定节拍，顺序输出即奏乐。
*/
